'use client';

import { useEffect, useState } from 'react';
import type { EvalResults } from '@/lib/contracts/types';
import fixture from '@/lib/contracts/fixtures/eval_results.json';
import { LocalTime } from './LocalTime';

const API = (process.env.NEXT_PUBLIC_API_URL ?? '').replace(/\/+$/, '');
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

type Source = 'api' | 'fixture';

/**
 * Evaluation table. Reads GET /api/eval/results when an API is configured and falls back to the committed
 * fixture. n === 0 means the eval has not run: we say so and show no numbers.
 */
export function EvalTable() {
  const [data, setData] = useState<{ results: EvalResults; source: Source }>({
    results: fixture as EvalResults,
    source: 'fixture',
  });

  useEffect(() => {
    if (!API) return;
    const ctrl = new AbortController();
    fetch(`${API}/api/eval/results`, { signal: ctrl.signal })
      .then((r) => (r.ok ? (r.json() as Promise<EvalResults>) : null))
      .then((results) => {
        if (results && Array.isArray(results.methods)) setData({ results, source: 'api' });
      })
      .catch(() => {
        // offline or no backend: keep the committed fixture
      });
    return () => ctrl.abort();
  }, []);

  const { results, source } = data;
  if (!results.n) {
    return (
      <p className="pending">
        Evaluation pending: generated by <code>{results.command || 'python eval/run_eval.py'}</code>. No accuracy is
        shown until it has run.
      </p>
    );
  }

  return (
    <>
      <figure className="tbl">
        <div className="table-wrap">
          <table>
            <thead>
              <tr>
                <th>Method</th>
                <th className="num">Runs</th>
                <th className="num">Top-1</th>
                <th className="num">Top-3</th>
                <th className="num">Abstained</th>
                <th className="num">Confident and wrong</th>
              </tr>
            </thead>
            <tbody>
              {results.methods.map((m) => (
                <tr key={m.name}>
                  <td>{m.name}</td>
                  <td className="num">{m.n}</td>
                  <td className="num">{pct(m.top1)}</td>
                  <td className="num">{pct(m.top3)}</td>
                  <td className="num">{pct(m.abstain_rate)}</td>
                  <td className="num">{pct(m.false_blame_rate)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        <figcaption>
          Blind runs, split {results.split}, {results.n} runs over {results.seeds.length} seeds. Abstaining counts as a
          miss for top-1 but not as a false blame. Source: {source === 'api' ? 'live API' : 'committed results file'}
          {results.generated_at ? (
            <>
              , generated <LocalTime iso={results.generated_at} />
            </>
          ) : null}
          . Reproduce with <code>{results.command}</code>.
        </figcaption>
      </figure>
      {results.sensitivity.length > 0 && (
        <figure className="tbl">
          <div className="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Weight</th>
                  <th className="num">Top-1 at -50%</th>
                  <th className="num">Top-1 at +50%</th>
                </tr>
              </thead>
              <tbody>
                {results.sensitivity.map((s) => (
                  <tr key={s.weight}>
                    <td className="mono">{s.weight}</td>
                    <td className="num">{pct(s.minus50_top1)}</td>
                    <td className="num">{pct(s.plus50_top1)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <figcaption>Sensitivity: each weight moved by half in either direction, the others unchanged.</figcaption>
        </figure>
      )}
    </>
  );
}
